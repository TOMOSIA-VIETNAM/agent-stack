import { join, posix } from 'node:path';
import { stringify as stringifyYaml } from 'yaml';
import type { ImportedSource } from './upstream.js';
import type { ResolvedStack } from './resolver.js';
import type { Selection, SelectedArtifact } from './selector.js';

export const MANIFEST_PATH = posix.join('.claude', 'aidd-manifest.json');
export const NOTICES_PATH = posix.join('.claude', 'THIRD-PARTY-NOTICES.md');
export const BEGIN_MARKER = '<!-- aidd:begin - generated by open-aidd, do not edit by hand -->';
export const END_MARKER = '<!-- aidd:end -->';

export interface PlannedFile {
  path: string;
  /** Inline contents, or a source path to copy verbatim (skill attachments). */
  contents?: string;
  copyFrom?: string;
}

export interface Manifest {
  generator: string;
  generatedAt: string;
  stack: { id: string; version?: string; origin: string }[];
  rules: { id: string; path: string }[];
  skills: { id: string; path: string }[];
  commands: { id: string; path: string }[];
  /** Other generated paths this run owns, e.g. third-party licence notices. */
  extras: string[];
  imported: { source: string; repo: string; ref: string }[];
}

export interface ComposedOutput {
  files: PlannedFile[];
  /** Paths owned by the previous run that this run no longer emits. */
  manifest: Manifest;
  claudeMdBlock: string;
}

function rulePath(entry: SelectedArtifact): string {
  const prefix = String(entry.artifact.meta.priority).padStart(2, '0');
  return posix.join('.claude', 'rules', `${prefix}-${entry.artifact.meta.id}.md`);
}

function skillDir(entry: SelectedArtifact): string {
  return posix.join('.claude', 'skills', entry.artifact.meta.id);
}

function ruleFile(entry: SelectedArtifact): string {
  const { meta, body } = entry.artifact;
  const applies =
    entry.matchedBy.length > 0
      ? `applies to: ${entry.matchedBy.join(', ')}`
      : 'applies to: all projects';
  // An imported rule is a whole document already; adding a heading above its own
  // would give the file two titles.
  const heading = body.startsWith('# ') ? [] : [`# ${meta.name}`, ''];
  return [
    originComment(entry, NOTICES_PATH),
    `<!-- ${applies} -->`,
    '',
    ...heading,
    body,
    '',
  ].join('\n');
}

function originComment(entry: SelectedArtifact, noticesPath: string): string {
  const { provenance, source } = entry.artifact;
  return provenance
    ? `<!-- imported from ${provenance.repo} at ${provenance.ref} - ${provenance.license}, ${provenance.copyright}. See ${noticesPath} -->`
    : `<!-- generated by open-aidd from knowledge/${source} - edit the knowledge base, not this file -->`;
}

/**
 * A skill authored here carries open-aidd's selection metadata alongside
 * Claude's own fields; only Claude's fields belong in the emitted skill.
 */
function skillFile(entry: SelectedArtifact): string {
  const { meta, body } = entry.artifact;
  const frontMatter = stringifyYaml({ name: meta.name, description: meta.description }).trim();
  return [
    '---',
    frontMatter,
    '---',
    '',
    originComment(entry, NOTICES_PATH),
    '',
    body,
    '',
  ].join('\n');
}

/** A command keeps its upstream front matter; only the origin comment is added. */
function commandFile(entry: SelectedArtifact): string {
  const frontMatter = stringifyYaml({ description: entry.artifact.meta.description }).trim();
  return [
    '---',
    frontMatter,
    '---',
    '',
    originComment(entry, `../${posix.basename(NOTICES_PATH)}`),
    '',
    entry.artifact.body,
    '',
  ].join('\n');
}

/** Licence notices for every source that contributed a selected artifact. */
function thirdPartyNotices(sources: ImportedSource[]): string {
  const sections = sources.map((source) =>
    [
      `## ${source.name}`,
      '',
      `Source: ${source.repo}`,
      `Commit: ${source.ref}`,
      `Licence: ${source.license}`,
      '',
      '```',
      source.licenseText,
      '```',
    ].join('\n'),
  );
  return [
    '# Third-party notices',
    '',
    'Content generated into this project, and the guidelines inlined into CLAUDE.md,',
    'were copied from the repositories below and remain under their original licences.',
    '',
    ...sections,
    '',
  ].join('\n');
}

/**
 * Drop a document's own leading title. A fragment is inlined under the project's
 * existing heading, so its title would be a second one partway down the file.
 */
function stripLeadingTitle(body: string): string {
  return body.startsWith('# ') ? body.slice(body.indexOf('\n') + 1).trimStart() : body;
}

/**
 * The managed block: guidance that applies to every project is inlined, so it is
 * in context without a hop; stack-specific rules stay separate files and are
 * @-imported, so the diff of a stack change stays readable.
 */
function claudeMdBlock(
  fragments: SelectedArtifact[],
  rules: { path: string; name: string }[],
): string {
  const lines: string[] = [BEGIN_MARKER, ''];

  for (const fragment of fragments) {
    lines.push(originComment(fragment, NOTICES_PATH), '');
    lines.push(stripLeadingTitle(fragment.artifact.body), '');
  }

  if (rules.length > 0) {
    lines.push('## Project rules', '', ...rules.map((rule) => `@${rule.path}`), '');
  }

  lines.push(END_MARKER);
  return lines.join('\n');
}

/** Merge the managed block into an existing CLAUDE.md without touching the rest. */
export function mergeClaudeMd(existing: string | undefined, block: string): string {
  if (!existing || existing.trim() === '') {
    return `${block}\n`;
  }
  const begin = existing.indexOf(BEGIN_MARKER);
  const end = existing.indexOf(END_MARKER);
  if (begin >= 0 && end > begin) {
    const before = existing.slice(0, begin);
    const after = existing.slice(end + END_MARKER.length);
    return `${before}${block}${after}`;
  }
  const separator = existing.endsWith('\n') ? '\n' : '\n\n';
  return `${existing}${separator}${block}\n`;
}

export function compose(
  stack: ResolvedStack,
  selection: Selection,
  generatorVersion: string,
  imported: ImportedSource[] = [],
): ComposedOutput {
  const files: PlannedFile[] = [];
  const ruleEntries = selection.rules.map((entry) => ({
    id: entry.artifact.meta.id,
    name: entry.artifact.meta.name,
    path: rulePath(entry),
  }));

  for (const entry of selection.rules) {
    files.push({ path: rulePath(entry), contents: ruleFile(entry) });
  }

  const skillEntries: { id: string; path: string }[] = [];
  for (const entry of selection.skills) {
    const dir = skillDir(entry);
    files.push({ path: posix.join(dir, 'SKILL.md'), contents: skillFile(entry) });
    skillEntries.push({ id: entry.artifact.meta.id, path: dir });
    for (const extra of entry.artifact.meta.files) {
      files.push({
        path: posix.join(dir, extra),
        copyFrom: join(entry.artifact.dir, extra),
      });
    }
  }

  const commandEntries: { id: string; path: string }[] = [];
  for (const entry of selection.commands) {
    const path = posix.join('.claude', 'commands', `${entry.artifact.meta.id}.md`);
    files.push({ path, contents: commandFile(entry) });
    commandEntries.push({ id: entry.artifact.meta.id, path });
  }

  const usedSources = new Set(
    [...selection.rules, ...selection.skills, ...selection.commands, ...selection.claudeMd]
      .map((entry) => entry.artifact.provenance?.source)
      .filter((source): source is string => source !== undefined),
  );
  const notices = imported.filter((source) => usedSources.has(source.name));
  const extras: string[] = [];
  if (notices.length > 0) {
    files.push({ path: NOTICES_PATH, contents: thirdPartyNotices(notices) });
    extras.push(NOTICES_PATH);
  }

  const manifest: Manifest = {
    generator: `open-aidd@${generatorVersion}`,
    generatedAt: new Date().toISOString(),
    stack: stack.technologies.map((tech) => ({
      id: tech.id,
      version: tech.version,
      origin: tech.origin,
    })),
    rules: ruleEntries.map(({ id, path }) => ({ id, path })),
    skills: skillEntries,
    commands: commandEntries,
    extras,
    imported: notices.map(({ name, repo, ref }) => ({ source: name, repo, ref })),
  };

  files.push({ path: MANIFEST_PATH, contents: `${JSON.stringify(manifest, null, 2)}\n` });

  return {
    files,
    manifest,
    claudeMdBlock: claudeMdBlock(selection.claudeMd, ruleEntries),
  };
}
